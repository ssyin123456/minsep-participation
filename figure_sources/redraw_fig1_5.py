# -*- coding: utf-8 -*-
r"""Redraw Figs. 1-5 in a uniform 1x2 layout from the published data.

Inputs: data/figures_data_v2.json, data/figures_data_v3.json and
data/recomputed_v2_curves.npz (regenerate with verify_data.py --full).
Submission figures are generated by redraw_all.py; this script keeps the
original 1x2 layout for diagnostics and writes ONLY to
data/sim_out/diagnostic/ so it never overwrites figs/fig*.jpg.
"""
import json, os, sys
import numpy as np
import matplotlib.pyplot as plt

ROOT = os.environ.get("MINSEP_ROOT") or os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
IN = os.path.join(ROOT, "data")
OUT = os.path.join(ROOT, "data", "sim_out", "diagnostic")
os.makedirs(OUT, exist_ok=True)
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from figstyle import apply_rc, new_canvas, finalize, save, PT

apply_rc()
v2 = json.load(open(f"{IN}/figures_data_v2.json"))
v3 = json.load(open(f"{IN}/figures_data_v3.json"))
Z = np.load(os.path.join(ROOT, "data", "recomputed_v2_curves.npz"))

RS = [0, 1, 2, 4, 8, 12, 16]
COL = plt.cm.viridis(np.linspace(0.0, 0.92, len(RS)))
MC, TH, REF = "#b2182b", "#2166ac", "#4d4d4d"
T = 1200
tgrid = np.arange(1, T + 1)
results = {}


def emit(fig, i, title):
    finalize(fig, title)
    issues = save(fig, os.path.join(OUT, "fig%d.jpg" % i))
    results[i] = issues
    print("  fig%-2d %-58s | 图例越界: %s" % (i, title, issues or "无"))


# ---------------------------------------------------------------- Fig. 1
fig, axes = new_canvas()
ax = axes[0]
for j, r in enumerate(RS):
    ax.semilogx(tgrid, Z[f"bias_{r}"], color=COL[j], lw=1.7, label=fr"$R={r}$")
ax.set(xlabel="round $t$", ylabel=r"$\|\mathbb{E}\hat\nu_t-\pi\|_{TV}$", ylim=(0, 0.9),
       title="(a) Bias of the expected empirical frequency")
ax.legend()
ax = axes[1]
for j, r in enumerate(RS):
    ax.loglog(tgrid, Z[f"tvar_{r}"], color=COL[j], lw=1.7, label=fr"$R={r}$")
    ax.axhline(v2["uniform"][str(r)]["pred"], color=COL[j], ls=":", lw=1.0, alpha=.85)
ax.plot([], [], "k:", lw=1.2, label="Theorem 2 (dotted)")
ax.set(xlabel="round $t$", ylabel=r"$t\,\mathrm{tr}\,\mathrm{Var}(\hat\nu_t)$",
       ylim=(1e-2, 3), title="(b) Asymptotic variance; dotted = Theorem 2")
ax.legend()
emit(fig, 1, "Bias and asymptotic variance under uniform availability")

# ---------------------------------------------------------------- Fig. 2
fig, axes = new_canvas()
ax = axes[0]
for j, r in enumerate(RS):
    ax.loglog(tgrid, Z[f"sgd_{r}"], color=COL[j], lw=1.7, label=fr"$R={r}$")
ax.set(xlabel="round $t$", ylabel=r"$\|w_t-a_{\mathrm{avg}}\|^2$",
       title="(a) Quadratic estimation error")
ax.legend()
ax = axes[1]
stats = v3["errorbars"]["stats"]
times = [11, 20, 40, 1200]
shades = ["#b2182b", "#ef8a62", "#67a9cf", "#2166ac"]
x = np.arange(len(RS))
w = 0.20
for j, (t, col) in enumerate(zip(times, shades)):
    m = np.array([stats[str(t)][str(r)]["mean"] for r in RS])
    s = np.array([stats[str(t)][str(r)]["sd"] for r in RS])
    ax.bar(x + (j - 1.5) * w, m, w, yerr=s, capsize=2.5, ecolor=col,
           error_kw=dict(lw=.8, alpha=.9), color=col, alpha=.92,
           label=fr"$t={t}$")
ax.set_yscale("log")
ax.set_ylim(3e-3, 6e1)
ax.set_xticks(x)
ax.set_xticklabels([str(r) for r in RS])
ax.set(xlabel="$R$", ylabel=r"$\|w_t-a_{\mathrm{avg}}\|^2$",
       title="(b) Four rounds; bars = one s.d. across 4000 trajectories")
ax.legend()
emit(fig, 2, "Quadratic estimation error: transient and steady state")

# ---------------------------------------------------------------- Fig. 4
fig, axes = new_canvas()
nu = v3["nonuniform"]
rr = np.array(sorted(int(k) for k in nu["results"]))
est = np.array([nu["results"][str(r)]["estimate"] for r in rr])
sp = np.array([nu["results"][str(r)]["spread"] for r in rr])
a0 = nu["analytic_R0"]
ax = axes[0]
ax.errorbar(rr, est, yerr=sp, fmt="o-", color=MC, lw=1.7, capsize=3,
            label=r"long-tailed $p_i\propto i^{-1.5}$, MC")
ax.axhline(a0, color=MC, ls=":", lw=1.2,
           label=r"analytic $R=0$: $1-\sum_i p_i^2$")
unif = (100 - rr) * (100 - rr - 1) / 100 ** 2
ax.plot(rr, unif, "s--", color=TH, lw=1.5,
        label=r"uniform $p$, Theorem 2 (scale reference)")
ax.set(xlabel="$R$", ylabel=r"$\sum_i\sigma_i^2(R)$",
       title=r"(a) Aggregate variance, $N=100$")
ax.legend()
ax = axes[1]
ck = ["1500", "2000", "2500", "3000"]
ckcol = plt.cm.Blues(np.linspace(.45, .9, len(ck)))
for j, c in enumerate(ck):
    vals = np.array([nu["results"][str(r)]["checkpoints"][c] for r in rr])
    ax.plot(rr, (vals - est) * 1e3, "o-", color=ckcol[j], lw=1.5, ms=4,
            label=fr"checkpoint $t={c}$")
ax.axhline(0.0, color="k", ls="-", lw=1.6, label="mean of four checkpoints")
ax.set(xlabel="$R$", ylabel=r"deviation from mean  $(\times 10^{-3})$",
       title="(b) Checkpoint spread behind the error bars in (a)")
ax.legend()
emit(fig, 3, "Aggregate variance under long-tailed availability")

# ---------------------------------------------------------------- Fig. 5
fig, axes = new_canvas()
small = v2["small_rho"]
rho = np.array([small[str(r)]["rho"] for r in [0, 1, 2, 5, 10]])
rv = np.array([small[str(r)]["ratio_var"] for r in [0, 1, 2, 5, 10]])
sg = np.array([small[str(r)]["sgd_ratio"] for r in [0, 1, 2, 5, 10]])
ax = axes[0]
ax.plot(rho, 1 - 2 * rho, "k--", lw=1.3, label=r"$1-2\rho$ (asymptotic)")
ax.plot(rho, rv, "o-", color=TH, lw=1.7,
        label=r"$\sigma^2(R)/\sigma^2(0)$, Theorem 2")
ax.plot(rho, sg, "s-", color=MC, lw=1.7,
        label=r"steady-state estimation error, ratio to $R=0$")
ax.set_ylim(0.7, 1.08)
ax.set(xlabel=r"$\rho=R/N$  ($N=100$)", ylabel="ratio to $R=0$",
       title=r"(a) Small-$\rho$ regime at $N=100$")
ax.legend()
ax = axes[1]
Ns = np.logspace(2, 6.2, 200)
for Rfix, col, mk in [(1, TH, "s"), (10, MC, "o")]:
    rat = (Ns - Rfix) * (Ns - Rfix - 1) / Ns ** 3 / ((Ns - 1) / Ns ** 2)
    ax.semilogx(Ns, 100 * (1 - rat), "-", color=col, lw=1.8,
                label=fr"$R={Rfix}$ (Theorem 2, analytic)")
pts = v3["rho_scale"]
for Rfix, col, mk in [(1, TH, "s"), (10, MC, "o")]:
    xs, ys = [], []
    for k, v in pts.items():
        Nx = int(k.split("_")[0][1:]); Rx = int(k.split("_")[1][1:])
        if Rx == Rfix:
            xs.append(Nx); ys.append(v["improve_pct"])
    ax.semilogx(xs, ys, mk, color=col, ms=6, mfc="white", mew=1.4,
                label=fr"$R={Rfix}$, tabulated values")
ax.set(xlabel=r"population size $N$ (log)", ylabel="variance reduction (%)",
       title=r"(b) Gain vanishes as $N$ grows ($\rho\to0$)")
ax.legend()
emit(fig, 4, "Small-rho regime and its large-N limit")

print("\n  图例全部在 axes 内:", all(not v for v in results.values()))
if any(results.values()):
    sys.exit(2)
